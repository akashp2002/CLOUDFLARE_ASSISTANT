def load_chunks() -> list[dict]:
    with open(CHUNKS_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


def find_supporting_chunks(doc_id: str, answer: str, question: str, chunks_by_doc: dict) -> list[str]:
    """Finds the chunk IDs within doc_id that best match the question/answer ground truth."""
    doc_chunks = chunks_by_doc.get(doc_id, [])
    if not doc_chunks:
        return []

    # Priority 1: Exact substring match of answer (case-insensitive)
    ans_lower = answer.lower().strip()
    exact_matches = [
        c["node_id"] for c in doc_chunks
        if ans_lower in c["text"].lower()
    ]
    if exact_matches:
        return exact_matches

    # Priority 2: Distinctive terms match
    # Find chunks containing key segments of the answer
    words = [w for w in ans_lower.replace(",", " ").replace(".", " ").split() if len(w) > 3]
    if words:
        scored = []
        for c in doc_chunks:
            text_lower = c["text"].lower()
            overlap = sum(1 for w in words if w in text_lower)
            if overlap > 0:
                scored.append((overlap, c["node_id"]))
        if scored:
            scored.sort(key=lambda x: -x[0])
            max_score = scored[0][0]
            top_ids = [node_id for score, node_id in scored if score >= max_score]
            return top_ids

    # Fallback: first chunk of doc
    return [doc_chunks[0]["node_id"]]


def main():
    print(f"Loading chunks from {CHUNKS_PATH}...")
    chunks = load_chunks()
    print(f"Loaded {len(chunks)} chunks.")

    # Index chunks by doc_id
    chunks_by_doc = {}
    doc_titles = {}
    doc_urls = {}
    for c in chunks:
        d = c["metadata"].get("doc_id")
        chunks_by_doc.setdefault(d, []).append(c)
        if d and "title" in c["metadata"]:
            doc_titles[d] = c["metadata"]["title"]
        if d and "source_url" in c["metadata"]:
            doc_urls[d] = c["metadata"]["source_url"]

    factual_dataset = []
    print(f"\nProcessing {len(FACTUAL_QA_DEFINITIONS)} factual questions across {len(chunks_by_doc)} documents...")

    for item in FACTUAL_QA_DEFINITIONS:
        doc_id = item["doc_id"]
        question = item["question"]
        answer = item["answer"]
        title = doc_titles.get(doc_id, doc_id)
        url = doc_urls.get(doc_id, "")

        matched_chunk_ids = find_supporting_chunks(doc_id, answer, question, chunks_by_doc)

        factual_dataset.append({
            "question": question,
            "ground_truth_answer": answer,
            "source_doc_id": doc_id,
            "source_title": title,
            "source_url": url,
            "relevant_chunk_ids": matched_chunk_ids,
            "reviewed": True,
            "expected_behavior": "should_answer"
        })

    # Add unanswerable questions
    full_dataset = factual_dataset + UNANSWERABLE_QUESTIONS

    # Save to eval_candidates.json
    candidates_path = EVAL_DIR / "eval_candidates.json"
    with open(candidates_path, "w", encoding="utf-8") as f:
        json.dump(factual_dataset, f, indent=2)
    print(f"Saved {len(factual_dataset)} candidate questions to {candidates_path}")

    # Save to eval_dataset.json
    dataset_path = EVAL_DIR / "eval_dataset.json"
    with open(dataset_path, "w", encoding="utf-8") as f:
        json.dump(full_dataset, f, indent=2)
    print(f"Saved {len(full_dataset)} total questions to {dataset_path}:")
    print(f"  - {len(factual_dataset)} factual questions ('should_answer') across 19 documents")
    print(f"  - {len(UNANSWERABLE_QUESTIONS)} unanswerable questions ('should_decline')")

    # Verification: check chunk coverage
    matched_count = sum(1 for q in factual_dataset if q["relevant_chunk_ids"])
    print(f"\nVerification: {matched_count}/{len(factual_dataset)} factual questions mapped to supporting chunk IDs.")


if __name__ == "__main__":
    main()

